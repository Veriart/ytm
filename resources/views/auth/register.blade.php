        function checkPasswordStrength(password) {
            const bars = [
                document.getElementById('str-1'),
                document.getElementById('str-2'),
                document.getElementById('str-3'),
                document.getElementById('str-4')
            ];
            const hint = document.getElementById('password-hint');
            
            // Reset
            bars.forEach(bar => bar.className = 'strength-bar flex-1 bg-surface-container-highest rounded-full');
            
            let strength = 0;
            if (password.length > 0) {
                if (password.length >= 6) strength++;
                if (password.length >= 10) strength++;
                if (/[0-9]/.test(password)) strength++;
                if (/[A-Z]/.test(password) && /[^A-Za-z0-9]/.test(password)) strength++;
            }

            const colors = ['bg-error', 'bg-secondary', 'bg-primary-container', 'bg-primary'];
            const labels = ['Weak', 'Moderate', 'Strong', 'Excellent'];

            for (let i = 0; i < strength; i++) {
                bars[i].classList.remove('bg-surface-container-highest');
                bars[i].classList.add(colors[strength - 1]);
            }

            if (strength > 0) {
                hint.textContent = `Strength: ${labels[strength - 1]}`;
                hint.className = `font-caption text-caption mt-1 font-bold text-${colors[strength-1].split('-')[1]}`;
            } else {
                hint.textContent = "Use 8 or more characters with a mix of letters and numbers.";
                hint.className = "font-caption text-caption text-on-surface-variant mt-1";
            }
        }
    </script>
